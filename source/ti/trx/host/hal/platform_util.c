void Plat_Util_blockCPU(uint32_t delayUs)
{
    const uint32_t delayCycles = ((CPU_FREQUENCY/(US_PER_SEC * CYCLES_PER_LOOP)) * delayUs);

    // Block CPU
    CPUdelay(delayCycles);
}
